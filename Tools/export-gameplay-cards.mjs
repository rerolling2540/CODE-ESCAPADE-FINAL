import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceRoot = path.join(root, 'Assets/Data/Cards/CARDS');
async function walk(folder) {
  const result = [];
  for (const entry of await fs.readdir(folder, { withFileTypes: true })) {
    const file = path.join(folder, entry.name);
    if (entry.isDirectory()) result.push(...await walk(file));
    else result.push(file);
  }
  return result;
}
function scalar(yaml, key, fallback = '') {
  const line = yaml.split('\n').find(line => line.startsWith(`  ${key}:`));
  if (!line) return fallback;
  const value = line.slice(line.indexOf(':') + 1).trim();
  if (value.startsWith('"')) return JSON.parse(value);
  if (value.startsWith("'")) return value.slice(1, -1).replaceAll("''", "'");
  if (value === '|' || value === '>') throw new Error(`Unsupported multiline field ${key}`);
  return value;
}
function number(yaml, key, fallback) {
  const value = Number(scalar(yaml, key, fallback));
  if (!Number.isFinite(value)) throw new Error(`Invalid numeric field ${key}`);
  return value;
}
const rows = [];
for (const file of (await walk(sourceRoot)).filter(file => file.endsWith('.asset')).sort()) {
  const yaml = (await fs.readFile(file, 'utf8')).replaceAll('\r\n', '\n');
  if (!yaml.includes('Assembly-CSharp::CardData')) continue;
  const guid = (await fs.readFile(file + '.meta', 'utf8')).match(/^guid: (\w+)/m)?.[1];
  if (!guid) throw new Error(`No GUID: ${file}`);
  const relative = path.relative(root, file).replaceAll('\\', '/');
  const character = relative.includes('/Warrior Cards/') ? 'warrior'
    : relative.includes('/Archer Cards/') ? 'archer'
    : relative.includes('/Mage Cards/') ? 'mage' : 'universal';
  const image = scalar(yaml, '<Image>k__BackingField');
  rows.push({
    game_card_key: guid,
    name: scalar(yaml, 'm_Name', path.basename(file, '.asset')),
    description: scalar(yaml, '<Description>k__BackingField'),
    mana: number(yaml, '<Mana>k__BackingField', 0),
    damage_type: number(yaml, 'damageType', 0),
    base_damage: number(yaml, 'baseDamage', 0),
    percent_damage: number(yaml, 'percentDamage', 0),
    damage_multiplier: number(yaml, 'damageMultiplier', 1),
    character_class: character,
    source_pack: 'CARDS', source_asset_path: relative,
    minimum_question_tier: number(yaml, 'minimumQuestionTier', 1),
    maximum_question_tier: number(yaml, 'maximumQuestionTier', 3),
    attack_vfx_type: number(yaml, 'attackVfxType', 0),
    icon_asset_guid: image.match(/guid: (\w+)/)?.[1] || '',
    icon_sprite_file_id: image.match(/fileID: (-?\d+)/)?.[1] || '',
    // Preserve the complete effect graph, targeting, stack counts, caps and
    // future custom fields without trying to reconstruct them from prose.
    card_definition: { format: 'unity-carddata-yaml-v1', asset_yaml: yaml }
  });
}
if (rows.length !== 60 || new Set(rows.map(row => row.game_card_key)).size !== rows.length)
  throw new Error(`Expected 60 distinct CARDS assets, found ${rows.length}`);
for (const row of rows) {
  if (row.mana < 0 || row.base_damage < 0 || row.percent_damage < 0 || row.damage_multiplier < 0)
    throw new Error(`Invalid card settings: ${row.name}`);
  if (![0, 1, 2, 3].includes(row.damage_type)) throw new Error(`Invalid damage type: ${row.name}`);
}
const types = {
  game_card_key: 'text', name: 'text', description: 'text', mana: 'integer',
  damage_type: 'integer', base_damage: 'integer', percent_damage: 'numeric', damage_multiplier: 'numeric',
  character_class: 'text', source_pack: 'text', source_asset_path: 'text',
  minimum_question_tier: 'integer', maximum_question_tier: 'integer', attack_vfx_type: 'integer',
  icon_asset_guid: 'text', icon_sprite_file_id: 'text', card_definition: 'jsonb'
};
const keys = Object.keys(types);
const newFields = keys.slice(8);
const data = JSON.stringify(rows);
if (data.includes('$cards_import$')) throw new Error('SQL delimiter collision');
const sql = `-- Generated by Tools/export-gameplay-cards.mjs from Assets/Data/Cards/CARDS.
-- Re-runnable import of 60 current cards. Preserves other rows, UUIDs, image URLs and player inventory.
-- Icons stay referenced by Unity GUID/fileID; this does not upload PNGs to Storage.
begin;
-- Match Unity's four supported damage modes, including target maximum HP.
alter table public.cards drop constraint if exists cards_damage_type_check;
alter table public.cards add constraint cards_damage_type_check
  check (damage_type in (0, 1, 2, 3));
alter table public.cards
${newFields.map(key => `  add column if not exists ${key} ${types[key]}`).join(',\n')};
create unique index if not exists cards_import_game_card_key_unique on public.cards(game_card_key);
insert into public.cards (${keys.join(', ')})
select ${keys.join(', ')}
from jsonb_to_recordset($cards_import$${data}$cards_import$::jsonb)
as imported(${keys.map(key => key + ' ' + types[key]).join(', ')})
on conflict (game_card_key) do update set
${keys.filter(key => key !== 'game_card_key').map(key => `  ${key} = excluded.${key}`).join(',\n')},
  updated_at = now();
commit;
select character_class, count(*) as imported_cards
from public.cards where source_pack = 'CARDS'
group by character_class order by character_class;
`;
const output = path.join(root, 'Assets/Data/Supabase/current_cards_seed.sql');
await fs.writeFile(output, sql);
await fs.writeFile(path.join(root, 'Assets/Data/Supabase/current_cards_export.json'), JSON.stringify(rows, null, 2));
console.log(`Exported ${rows.length} cards. ${Buffer.byteLength(sql)} bytes. ${output}`);
console.log(Object.fromEntries(['warrior', 'archer', 'mage'].map(hero => [hero, rows.filter(row => row.character_class === hero).length])));
